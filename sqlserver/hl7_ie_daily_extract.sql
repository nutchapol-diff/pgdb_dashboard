WITH page AS (
    SELECT TOP (?) LOG_ID, CREATED_ON, SENDER, RECEIVER, MESSAGE_TYPE,
           STATUS, ACKNOWLEDGMENT_CODE, IS_DELETED
    FROM dbo.RIS_HL7IELOG
    WHERE LOG_ID > ? AND LOG_ID <= ? ORDER BY LOG_ID
)
SELECT CAST(CREATED_ON AS date) AS event_day, SENDER, RECEIVER, MESSAGE_TYPE,
       STATUS AS status_code, ACKNOWLEDGMENT_CODE AS ack_code, IS_DELETED,
       COUNT_BIG(*) AS event_count, MAX(LOG_ID) AS page_key
FROM page
GROUP BY CAST(CREATED_ON AS date), SENDER, RECEIVER, MESSAGE_TYPE,
         STATUS, ACKNOWLEDGMENT_CODE, IS_DELETED
OPTION (RECOMPILE);
