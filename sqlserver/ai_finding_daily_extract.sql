WITH page AS (
    SELECT TOP (?) EXAM_RESULT_AI_DTL_ID, EXAM_RESULT_AI_ID,
           FINDING_NAME, FINDING_SCORE
    FROM dbo.RIS_EXAMRESULTAIDTL
    WHERE EXAM_RESULT_AI_DTL_ID > ? AND EXAM_RESULT_AI_DTL_ID <= ?
    ORDER BY EXAM_RESULT_AI_DTL_ID
)
SELECT CAST(a.CREATED_ON AS date) AS event_day, d.MODALITY_ID, f.FINDING_NAME,
       COUNT_BIG(*) AS event_count, COUNT_BIG(f.FINDING_SCORE) AS score_count,
       COALESCE(SUM(CAST(f.FINDING_SCORE AS decimal(38,10))), 0) AS score_sum,
       MIN(f.FINDING_SCORE) AS score_min, MAX(f.FINDING_SCORE) AS score_max,
       MAX(f.EXAM_RESULT_AI_DTL_ID) AS page_key
FROM page f
LEFT JOIN dbo.RIS_EXAMRESULTAI a ON a.EXAM_RESULT_AI_ID = f.EXAM_RESULT_AI_ID
LEFT JOIN dbo.RIS_ORDERDTL d ON d.ACCESSION_NO = a.ACCESSION_NO
GROUP BY CAST(a.CREATED_ON AS date), d.MODALITY_ID, f.FINDING_NAME
OPTION (RECOMPILE);
